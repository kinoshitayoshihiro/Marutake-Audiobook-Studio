# 章タイトルパターン（■で始まるタイトル）
CHAPTER_PATTERN = r'^■\s*(.+?)\s*$'


def detect_chapters(text: str) -> list:
    """テキストを章ごとに分割"""
    lines = text.split('\n')
    chapters = []
    current_chapter = None
    current_content = []
    
    pattern = re.compile(CHAPTER_PATTERN)
    
    for line in lines:
        stripped = line.strip()
        
        # 「おわり」は章としてスキップ
        if stripped == '■おわり':
            continue
        
        # 章タイトル検出（■　　一、夏草 のような形式）
        match = pattern.match(stripped)
        if match:
            # 前の章を保存
            if current_chapter:
                chapters.append({
                    "title": current_chapter,
                    "content": '\n'.join(current_content).strip()
                })
            # タイトルから「一、」などの番号部分を含めて取得
            current_chapter = match.group(1).strip()
            current_content = []
        else:
            current_content.append(line)
    
    # 最後の章を保存
    if current_chapter:
        chapters.append({
            "title": current_chapter,
            "content": '\n'.join(current_content).strip()
        })
    
    return chapters


